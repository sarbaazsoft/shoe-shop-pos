/**
 * RFC-4180 compliant CSV line splitter supporting quoted fields and escaped quotes.
 */
function splitCsvLine(line: string): string[] {
  const result: string[] = [];
  let current = '';
  let inQuotes = false;

  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === '"') {
      if (inQuotes && line[i + 1] === '"') {
        current += '"';
        i++;
      } else {
        inQuotes = !inQuotes;
      }
    } else if (ch === ',' && !inQuotes) {
      result.push(current.trim());
      current = '';
    } else {
      current += ch;
    }
  }
  result.push(current.trim());
  return result;
}

/**
 * Maps header aliases to canonical database schema column names.
 */
function normalizeHeaderKey(rawHeader: string): string {
  const clean = rawHeader
    .trim()
    .replace(/^["']|["']$/g, '')
    .trim();
  const lower = clean.toLowerCase().replace(/[\s-]+/g, '_');

  const map: Record<string, ProductCsvFieldKey> = {
    article: 'article',
    article_number: 'article',
    name: 'name',
    title: 'name',
    product_name: 'name',
    brand: 'brand',
    brand_name: 'brand',
    brandname: 'brand',
    category: 'category',
    category_name: 'category',
    categoryname: 'category',
    barcode: 'barcode',
    cost_price: 'cost_price',
    costprice: 'cost_price',
    selling_price: 'selling_price',
    sellingprice: 'selling_price',
    sale_price: 'selling_price',
    saleprice: 'selling_price',
    price: 'selling_price',
    min_price: 'min_price',
    minprice: 'min_price',
    min_sale_price: 'min_price',
    minsaleprice: 'min_price',
    max_price: 'max_price',
    maxprice: 'max_price',
    max_sale_price: 'max_price',
    maxsaleprice: 'max_price',
    total_stock: 'total_stock',
    totalstock: 'total_stock',
    stock: 'total_stock',
    low_stock_limit: 'low_stock_limit',
    lowstocklimit: 'low_stock_limit',
    primary_image_url: 'primary_image_url',
    primaryimageurl: 'primary_image_url',
    image_url: 'primary_image_url',
    description: 'description',
  };

  return map[lower] || lower;
}

/**
 * Parses CSV text and applies exact ProductFormModal & global companySettings
 * auto-generation, fallback, pricing validation, and duplicate detection rules.
 */
export function parseAndValidateProductsCsv(
  csvText: string,
  existingProducts: any[],
  companySettings: any,
  startingProductId: number
): {
  rows: ParsedCsvProductRow[];
  parseError?: string;
} {
  const lines = csvText
    .replace(/\r\n/g, '\n')
    .replace(/\r/g, '\n')
    .split('\n')
    .filter((l) => l.trim().length > 0);

  if (lines.length < 2) {
    return {
      rows: [],
      parseError: 'CSV file must contain a header row and at least one product data row.',
    };
  }

  const rawHeaders = splitCsvLine(lines[0]);
  const headers = rawHeaders.map(normalizeHeaderKey);

  const pricingMode: PricingMode =
    String(companySettings?.pricingMode || 'FIXED').toUpperCase() === 'NEGOTIABLE'
      ? 'NEGOTIABLE'
      : 'FIXED';

  const defaultLowStockLimit =
    Number(companySettings?.low_stock_limit ?? companySettings?.lowStockLimit) || 5;

  // Track used barcodes, and articles across current store DB + current CSV batch to prevent collisions
  const usedBarcodes = new Set<string>(
    existingProducts.map((p) => String(p.barcode || '').trim().toUpperCase()).filter(Boolean)
  );
  const usedArticles = new Set<string>(
    existingProducts.map((p) => String(p.article || '').trim().toUpperCase()).filter(Boolean)
  );

  // Track identifiers seen within the CSV file itself to flag intra-CSV duplicates
  const csvSeenBarcodes = new Map<string, number>();
  const csvSeenArticles = new Map<string, number>();

  let nextCandidateId = Math.max(1, startingProductId || 1);
  const parsedRows: ParsedCsvProductRow[] = [];

  for (let i = 1; i < lines.length; i++) {
    const cells = splitCsvLine(lines[i]);
    // Skip completely empty rows
    if (cells.every((c) => c.trim() === '')) continue;

    const rawRow: Record<string, string> = {};
    headers.forEach((h, idx) => {
      rawRow[h] = cells[idx] !== undefined ? cells[idx].trim() : '';
    });

    const autoGeneratedFields: string[] = [];
    const validationErrors: Record<string, string> = {};

    // 1. Check if this row matches an existing product in this store (by barcode or article)
    const inputBarcode = (rawRow.barcode || '').trim();
    const inputArticle = (rawRow.article || '').trim().toUpperCase();

    if (inputBarcode && csvSeenBarcodes.has(inputBarcode.toUpperCase())) {
      validationErrors.barcode = `Duplicate barcode "${inputBarcode}" in CSV (also on row ${csvSeenBarcodes.get(inputBarcode.toUpperCase())})`;
    }
    if (inputArticle && csvSeenArticles.has(inputArticle)) {
      validationErrors.article = `Duplicate article "${inputArticle}" in CSV (also on row ${csvSeenArticles.get(inputArticle)})`;
    }

    let existingProduct: any = undefined;
    let duplicateMatchType: 'barcode' | 'article' | undefined = undefined;

    if (inputBarcode) {
      existingProduct = existingProducts.find(
        (p) => String(p.barcode || '').trim().toUpperCase() === inputBarcode.toUpperCase()
      );
      if (existingProduct) duplicateMatchType = 'barcode';
    }
    if (!existingProduct && inputArticle) {
      existingProduct = existingProducts.find(
        (p) => String(p.article || '').trim().toUpperCase() === inputArticle
      );
      if (existingProduct) duplicateMatchType = 'article';
    }

    // Check if row matches an existing product on one identifier, while ANOTHER identifier on the row collides with a DIFFERENT store product
    if (existingProduct) {
      if (inputBarcode) {
        const otherBarcodeMatch = existingProducts.find(
          (p) =>
            Number(p.id) !== Number(existingProduct.id) &&
            String(p.barcode || '').trim().toUpperCase() === inputBarcode.toUpperCase()
        );
        if (otherBarcodeMatch) {
          validationErrors.barcode = `Barcode "${inputBarcode}" already belongs to another product in this store (${otherBarcodeMatch.name || otherBarcodeMatch.article})`;
        }
      }
      if (inputArticle) {
        const otherArticleMatch = existingProducts.find(
          (p) =>
            Number(p.id) !== Number(existingProduct.id) &&
            String(p.article || '').trim().toUpperCase() === inputArticle
        );
        if (otherArticleMatch) {
          validationErrors.article = `Article "${inputArticle}" already belongs to another product in this store (${otherArticleMatch.name || otherArticleMatch.article})`;
        }
      }
    }

    const rowProductId =
      existingProduct?.tenantProductNo ||
      existingProduct?.tenant_product_no ||
      existingProduct?.id ||
      nextCandidateId;

    // 2. Brand (fallback from ProductFormModal: 'Unbranded')
    let brand = (rawRow.brand || '').trim();
    if (!brand) {
      brand = existingProduct?.brand || existingProduct?.brandName || 'Unbranded';
      autoGeneratedFields.push('brand');
    }

    // 3. Category (fallback from ProductFormModal: 'Men')
    let category = (rawRow.category || '').trim();
    if (!category) {
      category = existingProduct?.category || existingProduct?.categoryName || 'Men';
      autoGeneratedFields.push('category');
    }

    // 4. Article (auto-generated via parseCategoryPrefix & generateSuggestedArticle from src/utils/footwear.ts)
    const catPfx = parseCategoryPrefix(category);
    let candidateArticleId = rowProductId;
    let storeStandardArticle = generateSuggestedArticle(catPfx, candidateArticleId);
    while (!existingProduct && usedArticles.has(storeStandardArticle.toUpperCase())) {
      candidateArticleId++;
      storeStandardArticle = generateSuggestedArticle(catPfx, candidateArticleId);
    }
    let article = inputArticle;
    if (!article) {
      if (existingProduct?.article) {
        article = String(existingProduct.article).toUpperCase();
      } else {
        article = storeStandardArticle;
      }
      autoGeneratedFields.push('article');
    }
    usedArticles.add(article.toUpperCase());
    if (inputArticle && !csvSeenArticles.has(inputArticle)) {
      csvSeenArticles.set(inputArticle, i);
    }

    // 5. Name / Title (fallback from ProductFormModal: cleanArticle)
    let name = (rawRow.name || '').trim();
    if (!name) {
      name = existingProduct?.name || article;
      autoGeneratedFields.push('name');
    }

    // 6. Barcode (auto-generated via generateCode128Barcode: [2-Letter Category]-[Exact Product ID], no prefix)
    let barcode = inputBarcode;
    if (!barcode) {
      if (existingProduct?.barcode) {
        barcode = String(existingProduct.barcode);
      } else {
        let candidateId = rowProductId;
        let gen = generateCode128Barcode(candidateId, catPfx);
        while (usedBarcodes.has(gen.barcode.toUpperCase())) {
          candidateId++;
          gen = generateCode128Barcode(candidateId, catPfx);
        }
        barcode = gen.barcode;
      }
      autoGeneratedFields.push('barcode');
    } else {
      const analysis = analyzeBarcode(barcode);
      if (!analysis.isValid) {
        validationErrors.barcode = analysis.error || 'Invalid barcode format.';
      }
    }
    usedBarcodes.add(barcode.toUpperCase());
    if (inputBarcode && !csvSeenBarcodes.has(inputBarcode.toUpperCase())) {
      csvSeenBarcodes.set(inputBarcode.toUpperCase(), i);
    }

    if (!existingProduct) {
      nextCandidateId++;
    }

    // 8. Numeric validation & fallbacks for stock fields
    const rawStockStr = rawRow.total_stock ?? '';
    let total_stock = 0;
    if (rawStockStr === '') {
      total_stock = 0;
      autoGeneratedFields.push('total_stock');
    } else if (!/^-?\d+(\.\d+)?$/.test(rawStockStr)) {
      validationErrors.total_stock = `Invalid number "${rawStockStr}" in total_stock`;
    } else {
      const parsed = Math.round(Number(rawStockStr));
      if (parsed < 0) {
        validationErrors.total_stock = 'total_stock cannot be negative';
      } else {
        total_stock = parsed;
      }
    }

    const rawLowStockStr = rawRow.low_stock_limit ?? '';
    let low_stock_limit = defaultLowStockLimit;
    if (rawLowStockStr === '') {
      low_stock_limit = existingProduct?.lowStockLimit ?? defaultLowStockLimit;
      autoGeneratedFields.push('low_stock_limit');
    } else if (!/^-?\d+(\.\d+)?$/.test(rawLowStockStr)) {
      validationErrors.low_stock_limit = `Invalid number "${rawLowStockStr}" in low_stock_limit`;
    } else {
      const parsed = Math.round(Number(rawLowStockStr));
      if (parsed < 0) {
        validationErrors.low_stock_limit = 'low_stock_limit cannot be negative';
      } else {
        low_stock_limit = parsed;
      }
    }

    // 9. Numeric validation & fallbacks for pricing fields
    const parseNumericField = (
      fieldKey: 'cost_price' | 'selling_price' | 'min_price' | 'max_price',
      rawVal: string
    ): number | undefined => {
      if (rawVal === '') return undefined;
      if (!/^-?\d+(\.\d+)?$/.test(rawVal)) {
        validationErrors[fieldKey] = `Invalid numeric value "${rawVal}"`;
        return undefined;
      }
      const num = Number(rawVal);
      if (!Number.isFinite(num)) {
        validationErrors[fieldKey] = `Invalid numeric value "${rawVal}"`;
        return undefined;
      }
      return Math.round(num);
    };

    const parsedCost = parseNumericField('cost_price', rawRow.cost_price ?? '');
    const parsedSelling = parseNumericField('selling_price', rawRow.selling_price ?? '');
    const parsedMin = parseNumericField('min_price', rawRow.min_price ?? '');
    const parsedMax = parseNumericField('max_price', rawRow.max_price ?? '');

    let cost_price = parsedCost ?? 0;
    if (parsedCost === undefined && !validationErrors.cost_price) {
      cost_price =
        existingProduct?.costPrice ??
        existingProduct?.cost_price ??
        0;
      autoGeneratedFields.push('cost_price');
    }

    let effSelling = parsedSelling;
    let effMin = parsedMin;
    let effMax = parsedMax;

    if (pricingMode === 'FIXED') {
      if (effMax === undefined && !validationErrors.max_price) {
        effMax = effSelling ?? effMin ?? existingProduct?.maxPrice ?? existingProduct?.max_price ?? cost_price;
        autoGeneratedFields.push('max_price');
      }
      if (effMin === undefined && !validationErrors.min_price) {
        autoGeneratedFields.push('min_price');
      }
      if (effMax === undefined && !validationErrors.max_price) {
        autoGeneratedFields.push('max_price');
      }
    } else {
      if (effMin === undefined && !validationErrors.min_price) {
        effMin =
          effSelling ??
          existingProduct?.minPrice ??
          existingProduct?.min_price ??
          cost_price;
        autoGeneratedFields.push('min_price');
      }
      if (effMax === undefined && !validationErrors.max_price) {
        effMax =
          effSelling ??
          effMin ??
          existingProduct?.maxPrice ??
          existingProduct?.max_price ??
          cost_price;
        autoGeneratedFields.push('max_price');
      }
      if (effSelling === undefined && !validationErrors.selling_price) {
        effSelling = effMax;
        autoGeneratedFields.push('selling_price');
      }
    }

    let finalSellingPrice = effSelling ?? cost_price;
    let finalMinPrice = effMin ?? finalSellingPrice;
    let finalMaxPrice = effMax ?? finalSellingPrice;

    // Run strict Zod pricing validation if no raw numeric syntax error occurred on price fields
    const hasRawPriceSyntaxError = Boolean(
      validationErrors.cost_price ||
        validationErrors.selling_price ||
        validationErrors.min_price ||
        validationErrors.max_price
    );

    if (!hasRawPriceSyntaxError) {
      const priceValidation = validateAndNormalizeProductPricing({
        pricingMode,
        costPrice: cost_price,
        minPrice: effMin,
        maxPrice: effMax,
      });

      if (!priceValidation.success || !priceValidation.data) {
        if (priceValidation.fieldErrors.costPrice) {
          validationErrors.cost_price = priceValidation.fieldErrors.costPrice;
        }
        if (priceValidation.fieldErrors.sellingPrice) {
          validationErrors.selling_price = priceValidation.fieldErrors.sellingPrice;
        }
        if (priceValidation.fieldErrors.minPrice) {
          validationErrors.min_price = priceValidation.fieldErrors.minPrice;
        }
        if (priceValidation.fieldErrors.maxPrice) {
          validationErrors.max_price = priceValidation.fieldErrors.maxPrice;
        }
        if (
          !validationErrors.cost_price &&
          !validationErrors.selling_price &&
          !validationErrors.min_price &&
          !validationErrors.max_price &&
          priceValidation.error
        ) {
          validationErrors.selling_price = priceValidation.error;
        }
      } else {
        cost_price = priceValidation.data.costPrice;
        finalSellingPrice = priceValidation.data.sellingPrice;
        finalMinPrice = priceValidation.data.minPrice;
        finalMaxPrice = priceValidation.data.maxPrice;
      }
    }

    const isValid = Object.keys(validationErrors).length === 0;

    parsedRows.push({
      rowNumber: i,
      rawRow,
      article,
      name,
      brand,
      category,
      barcode,
      cost_price,
      selling_price: finalSellingPrice,
      min_price: finalMinPrice,
      max_price: finalMaxPrice,
      total_stock,
      low_stock_limit,
      primary_image_url: rawRow.primary_image_url || '',
      description: rawRow.description || '',
      autoGeneratedFields,
      validationErrors,
      isValid,
      isDuplicate: Boolean(existingProduct),
      duplicateMatchType,
      existingProduct,
    });
  }

  return { rows: parsedRows };
}
